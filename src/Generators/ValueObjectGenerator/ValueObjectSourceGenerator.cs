using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;

namespace ValueObjectGenerator;

#pragma warning disable CA1310
#pragma warning disable IDE0008 // Use explicit type
#pragma warning disable IDE0011 // Add braces
[Generator]
public class ValueObjectSourceGenerator : IIncrementalGenerator
{
    private const string AttributeSource = @"// <auto-generated/>
#pragma warning disable
#nullable enable

using System;

namespace ValueObjectGenerator.Attributes
{
    [AttributeUsage(AttributeTargets.Class, Inherited = false, AllowMultiple = false)]
    internal sealed class GenerateValueObjectAttribute : Attribute { }
}";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(ctx =>
            ctx.AddSource("GenerateValueObjectAttribute.g.cs", SourceText.From(AttributeSource, Encoding.UTF8)));

        var provider = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: (s, _) => s is ClassDeclarationSyntax c && c.Modifiers.Any(m => m.Text == "partial"),
                transform: (ctx, _) => GetValueObjectSymbol(ctx))
            .Where(m => m != null);

        var collected = provider.Select((s, _) => s!).Collect();

        context.RegisterSourceOutput(collected, (spc, symbols) =>
        {
            foreach (var symbol in symbols)
            {
                var code = GenerateCode(symbol);
                spc.AddSource(symbol.Name + ".ValueObject.g.cs", SourceText.From(code, Encoding.UTF8));
            }
        });
    }

    private INamedTypeSymbol? GetValueObjectSymbol(GeneratorSyntaxContext context)
    {
        var classDecl = (ClassDeclarationSyntax)context.Node;
        if (context.SemanticModel.GetDeclaredSymbol(classDecl) is not INamedTypeSymbol symbol)
            return null;

        var hasAttr = symbol.GetAttributes().Any(a =>
            a.AttributeClass?.Name == "GenerateValueObjectAttribute" ||
            a.AttributeClass?.Name == "GenerateValueObject");
        if (!hasAttr) return null;

        var baseType = symbol.BaseType;
        while (baseType != null)
        {
            if (baseType.Name == "ValueObject") return symbol;
            baseType = baseType.BaseType;
        }
        return null;
    }

    private string GenerateCode(INamedTypeSymbol symbol)
    {
        var ns = symbol.ContainingNamespace.ToDisplayString();
        var name = symbol.Name;
        var vis = symbol.DeclaredAccessibility.ToString().ToLowerInvariant();

        var props = symbol.GetMembers()
            .OfType<IPropertySymbol>()
            .Where(p => !p.IsStatic && !p.IsIndexer && p.SetMethod != null &&
                        p.DeclaredAccessibility == Accessibility.Public &&
                        p.Name != "HasChanges" && !p.Name.StartsWith("_"))
            .ToList();

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#pragma warning disable");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Linq;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine();
        sb.AppendLine("namespace " + ns);
        sb.AppendLine("{");
        sb.AppendLine("    " + vis + " partial class " + name);
        sb.AppendLine("    {");
        sb.AppendLine("        [System.ComponentModel.DataAnnotations.Schema.NotMapped]");
        sb.AppendLine("        public bool HasChanges { get; private set; }");
        sb.AppendLine("        private " + name + "? _origin;");
        sb.AppendLine();

        // Create method
        sb.AppendLine("        public static " + name + " Create(");
        sb.AppendLine("            " + name + "? origin = null,");
        for (int i = 0; i < props.Count; i++)
        {
            var p = props[i];
            var nullable = MakeNullable(p.Type);
            var comma = i < props.Count - 1 ? "," : ")";
            sb.AppendLine("            " + nullable + " " + CamelCase(p.Name) + " = null" + comma);
        }
        sb.AppendLine("        {");
        sb.AppendLine("            var instance = new " + name);
        sb.AppendLine("            {");
        foreach (var p in props)
        {
            var camel = CamelCase(p.Name);
            var assign = GetAssign(p, camel);
            sb.AppendLine("                " + p.Name + " = " + assign + ",");
        }
        sb.AppendLine("            };");
        sb.AppendLine("            instance._origin = origin;");
        sb.AppendLine("            instance.HasChanges = origin == null || !instance.Equals(origin);");
        sb.AppendLine("            return instance;");
        sb.AppendLine("        }");
        sb.AppendLine();

        // GetChanges
        sb.AppendLine("        public IReadOnlyList<string> GetChanges()");
        sb.AppendLine("        {");
        sb.AppendLine("            var changes = new List<string>();");
        sb.AppendLine("            if (_origin == null) return changes;");
        foreach (var p in props)
        {
            var t = p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            if (IsListType(p.Type))
            {
                sb.AppendLine("            if (!(this." + p.Name + " ?? Enumerable.Empty<" + GetListElementTypeName(p.Type) + ">()).SequenceEqual(_origin." + p.Name + " ?? Enumerable.Empty<" + GetListElementTypeName(p.Type) + ">()))");
                sb.AppendLine("                changes.Add(nameof(" + p.Name + "));");
            }
            else
            {
                sb.AppendLine("            if (!EqualityComparer<" + t + ">.Default.Equals(this." + p.Name + ", _origin." + p.Name + "))");
                sb.AppendLine("                changes.Add(nameof(" + p.Name + "));");
            }
        }
        sb.AppendLine("            return changes;");
        sb.AppendLine("        }");
        sb.AppendLine();

        // With
        sb.AppendLine("        public " + name + " With(");
        for (int i = 0; i < props.Count; i++)
        {
            var p = props[i];
            var nullable = MakeNullable(p.Type);
            var comma = i < props.Count - 1 ? "," : ")";
            sb.AppendLine("            " + nullable + " " + CamelCase(p.Name) + " = null" + comma);
        }
        sb.AppendLine("        {");
        sb.AppendLine("            return Create(origin: this,");
        for (int i = 0; i < props.Count; i++)
        {
            var p = props[i];
            var camel = CamelCase(p.Name);
            var comma = i < props.Count - 1 ? "," : ");";
            sb.AppendLine("                " + camel + ": " + camel + comma);
        }
        sb.AppendLine("        }");
        sb.AppendLine();

        // GetEqualityComponents
        sb.AppendLine("        protected override IEnumerable<object?> GetEqualityComponents()");
        sb.AppendLine("        {");
        foreach (var p in props)
        {
            if (IsListType(p.Type))
            {
                sb.AppendLine("            foreach (var item in " + p.Name + " ?? Enumerable.Empty<" + GetListElementTypeName(p.Type) + ">())");
                sb.AppendLine("                yield return item;");
            }
            else
            {
                sb.AppendLine("            yield return " + p.Name + ";");
            }
        }
        sb.AppendLine("        }");

        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    private string MakeNullable(ITypeSymbol type)
    {
        var name = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        if (name.EndsWith("?")) return name;
        return name + "?";
    }

    private string GetAssign(IPropertySymbol prop, string camel)
    {
        var isNullable = prop.Type.NullableAnnotation == NullableAnnotation.Annotated ||
                         prop.Type.ToDisplayString().EndsWith("?");

        if (isNullable)
            return camel + " ?? origin?." + prop.Name;

        if (prop.Type.IsValueType)
            return camel + " ?? origin?." + prop.Name + " ?? default";

        return camel + " ?? origin?." + prop.Name + " ?? default!";
    }

    private string CamelCase(string s)
    {
        if (string.IsNullOrEmpty(s)) return s;
        return char.ToLowerInvariant(s[0]) + s.Substring(1);
    }

    private bool IsListType(ITypeSymbol type)
    {
        if (type is not INamedTypeSymbol namedType || !namedType.IsGenericType)
            return false;

        string originalDef = namedType.OriginalDefinition.ToDisplayString();
        return originalDef == "System.Collections.Generic.List<T>"
            || originalDef == "System.Collections.Generic.IList<T>"
            || originalDef == "System.Collections.Generic.IReadOnlyList<T>"
            || originalDef == "System.Collections.Generic.ICollection<T>"
            || originalDef == "System.Collections.Generic.IEnumerable<T>";
    }

    private string GetListElementTypeName(ITypeSymbol type)
    {
        if (type is INamedTypeSymbol namedType && namedType.IsGenericType && namedType.TypeArguments.Length == 1)
            return namedType.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        return "object";
    }
}
